"""Non-dominated sorting and crowding distance for NSGA-II.

All objectives are minimised. Generated by the bench and then corrected: the
first version computed a backward difference in `crowding_distance` where the
algorithm specifies a central one, which passed a test suite that only checked
the shape of the answer. See tests/test_pareto.py TestCrowdingDistanceExactValues.
"""

import numpy as np


def dominates(a: np.ndarray, b: np.ndarray) -> bool:
    """True if `a` dominates `b`: no worse on all objectives, better on one."""
    # bool() because numpy's and/or return np.bool_, which is not `is True`
    # and surprises callers that identity-check the result.
    return bool(np.all(a <= b) and np.any(a < b))


def non_dominated_sort(points: np.ndarray) -> list[list[int]]:
    """Non‑dominated sorting (NSGA‑II)."""
    n = points.shape[0]
    if n == 0:
        return []
    if n == 1:
        return [[0]]
    # domination count and dominated set
    dom_count = np.zeros(n, dtype=int)
    dominated = [[] for _ in range(n)]
    for i in range(n):
        for j in range(n):
            if i == j:
                continue
            if dominates(points[i], points[j]):
                dominated[i].append(j)
            elif dominates(points[j], points[i]):
                dom_count[i] += 1
    fronts: list[list[int]] = []
    # first front
    current = [i for i in range(n) if dom_count[i] == 0]
    while current:
        fronts.append(sorted(current))
        next_front: list[int] = []
        for i in current:
            for j in dominated[i]:
                dom_count[j] -= 1
                if dom_count[j] == 0:
                    next_front.append(j)
        current = next_front
    return fronts


def crowding_distance(points: np.ndarray) -> np.ndarray:
    """Crowding distance for NSGA‑II (all objectives minimised)."""
    n, m = points.shape
    if n == 0:
        return np.array([], dtype=float)
    distances = np.zeros(n, dtype=float)
    for k in range(m):
        idx = np.argsort(points[:, k])
        sorted_vals = points[idx, k]
        # boundary points
        distances[idx[0]] = np.inf
        distances[idx[-1]] = np.inf
        # Spread of this objective across the front. Zero means every point
        # shares the value, so it separates nothing and contributes nothing --
        # skipping also avoids dividing by zero.
        denom = sorted_vals[-1] - sorted_vals[0]
        if denom == 0:
            continue
        # Central difference: each interior point's share is the gap spanned by
        # its two neighbours, f[i+1] - f[i-1]. A backward difference
        # (f[i] - f[i-1]) understates crowding and biases selection toward one
        # end of the front.
        diff = sorted_vals[2:] - sorted_vals[:-2]
        distances[idx[1:-1]] += diff / denom
    return distances
